export type LocaleKey = keyof typeof strings;

let globalLocale: LocaleKey = 'en';

export function setGlobalLocale(locale: LocaleKey): void {
  globalLocale = locale;
}

export function t(key: keyof typeof strings['en'], locale: LocaleKey = globalLocale): string {
  const dict = strings[locale] || strings.en;
  return dict[key] || strings.en[key] || key;
}
